CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    price NUMERIC(19, 2) NOT NULL,
    type VARCHAR(16) NOT NULL,
    author VARCHAR(255),
    page_count INTEGER,
    publisher VARCHAR(255),
    issue_number INTEGER,
    CONSTRAINT products_name_not_blank CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT products_price_nonnegative CHECK (price >= 0),
    CONSTRAINT products_type_fields CHECK (
        (type = 'book' AND author IS NOT NULL AND LENGTH(TRIM(author)) > 0
            AND page_count IS NOT NULL AND page_count > 0
            AND publisher IS NULL AND issue_number IS NULL)
        OR
        (type = 'journal' AND publisher IS NOT NULL AND LENGTH(TRIM(publisher)) > 0
            AND issue_number IS NOT NULL AND issue_number > 0
            AND author IS NULL AND page_count IS NULL)
    )
);
